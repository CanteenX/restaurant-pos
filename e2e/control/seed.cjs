function fail() {
  process.stderr.write('Control browser fixture seed failed.\n');
  process.exitCode = 1;
}

// The launcher passes the dynamic port from its own disposable Docker container.
const port = process.argv[2];
const fixtureUrl = 'postgresql://fixture:fixture@127.0.0.1:' + port + '/fixture';
if (process.argv.length !== 3 || !/^[0-9]{5}$/.test(port) || Number(port) < 32768 ||
    Number(port) > 65535 || process.env.CONTROL_DATABASE_URL !== fixtureUrl) {
  fail();
  return;
}
const { createHash, randomUUID } = require('node:crypto');
const apiModules = '../../apps/control-api/node_modules/';
const { PrismaClient } = require(apiModules + '.prisma/control-client');
const { hash } = require(apiModules + 'bcrypt');
const { sealSecret } = require('../../packages/types/dist/node/totp');
const { CONTROL_PERMISSIONS } = require('../../packages/types/dist/permissions');
// Per-run secrets for the client-controls staff, generated by control-qa.sh.
const controlsPassphrase = process.env.CONTROL_FIXTURE_PASSPHRASE;
const controlsTotpSeed = process.env.CONTROL_FIXTURE_TOTP_SEED;
if (!controlsPassphrase || !/^[A-Z2-7]{32}$/.test(controlsTotpSeed ?? '')) {
  fail();
  return;
}
const db = new PrismaClient({ datasourceUrl: fixtureUrl });

async function seed() {
  const passwordHash = await hash('browser fixture passphrase', 12);
  await require('./helpdesk-fixture.cjs')(db, passwordHash);
  await require('./audit-fixture.cjs')(db, passwordHash);
  await require('./portal-support-fixture.cjs')(db, passwordHash);
  const controlsPasswordHash = await hash(controlsPassphrase, 12);
  const ownerId = randomUUID(), readerId = randomUUID(), operationsId = randomUUID();
  const read = ['cc.business.read', 'cc.plan.read'];
  const encryptedSeed = sealSecret('JBSWY3DPEHPK3PXPJBSWY3DPEHPK3PXP', process.env.CONTROL_AUTH_KEY + readerId);
  const controlsId = randomUUID();
  const teamAdminId = randomUUID();
  const adminRole = await db.staffRole.findUniqueOrThrow({ where: { key: 'admin' } });
  await db.staff.createMany({ data: [
    { id: teamAdminId, email: 'team-admin@example.test', passwordHash: controlsPasswordHash, name: 'Team owner',
      roleId: adminRole.id, grants: adminRole.grants,
      encryptedSeed: sealSecret(controlsTotpSeed, process.env.CONTROL_AUTH_KEY + teamAdminId) },
    { id: controlsId, email: 'client-controls@example.test', passwordHash: controlsPasswordHash,
      grants: ['cc.business.read', 'cc.hosted.read', 'cc.hosted.manage', 'cc.portal.read', 'cc.portal.create', 'cc.portal.manage', 'cc.ticket.read'],
      encryptedSeed: sealSecret(controlsTotpSeed, process.env.CONTROL_AUTH_KEY + controlsId) },
    { id: ownerId, email: 'owner@example.test', passwordHash, grants: [...read, 'cc.business.manage', 'cc.plan.manage'] },
    { id: readerId, email: 'reader@example.test', passwordHash, grants: read, encryptedSeed },
    { id: operationsId, email: 'operations@example.test', passwordHash,
      grants: ['cc.business.read', 'cc.business.manage', 'cc.plan.read', 'cc.ticket.read', 'cc.billing.read', 'cc.billing.manage', 'cc.hosted.read', 'cc.hosted.manage', 'cc.portal.read', 'cc.portal.create', 'cc.portal.manage']
        .filter((permission) => CONTROL_PERMISSIONS.includes(permission)),
      encryptedSeed: sealSecret('JBSWY3DPEHPK3PXPJBSWY3DPEHPK3PXP', process.env.CONTROL_AUTH_KEY + operationsId) },
  ] });
  const customRole = await db.staffRole.create({ data: {
    key: 'qa-ticket-reader', name: 'QA Ticket Reader', grants: ['cc.ticket.read'],
  } });
  const seededRoles = await db.staffRole.findMany({
    where: { key: { in: ['admin', 'manager', 'support', 'marketing'] } },
  });
  if (seededRoles.length !== 4) throw new Error('Missing starting role in the browser fixture');
  await db.staff.createMany({ data: [...seededRoles, customRole].map((role) => {
    const id = randomUUID();
    return { id, email: 'role-' + (role.id === customRole.id ? 'custom' : role.key) + '@example.test',
      name: role.name + ' browser fixture', passwordHash: controlsPasswordHash, roleId: role.id, grants: role.grants,
      encryptedSeed: sealSecret(controlsTotpSeed, process.env.CONTROL_AUTH_KEY + id) };
  }) });
  await db.staffEnrollmentProof.create({ data: { staffId: ownerId, expiresAt: new Date(Date.now() + 900_000),
    digest: createHash('sha256').update(Buffer.alloc(32, 42)).digest() } });
  const business = await db.business.create({ data: {
    id: randomUUID(), legalName: 'Fixture Bistro Pvt Ltd', displayName: 'Fixture Bistro',
  } });
  await db.outlet.create({ data: { id: randomUUID(), businessId: business.id, displayName: 'Market Outlet', timeZone: 'UTC' } });
}

void seed().finally(() => db.$disconnect()).catch(fail);
